/**
 * Return the recommended sequence preset path for a given ScaleCut format.
 * Premiere Pro ships with built-in preset .sqpreset files.
 *
 * Status: 📋 PLANNED — preset paths are installation-dependent.
 *
 * @param  {string} format  "9x16", "1x1", or "16x9"
 * @return {Object}  { width, height, presetHint }
 */
ScaleCut.getPresetForFormat = function(format) {
    var presets = {
        "9x16":  { width: 1080, height: 1920, presetHint: "Vertical (1080x1920)" },
        "1x1":   { width: 1080, height: 1080, presetHint: "Square (1080x1080)"   },
        "16x9":  { width: 1920, height: 1080, presetHint: "HD 1080p (1920x1080)" }
    };
    return presets[format] || presets["16x9"];
};


/**
 * Build the Premiere sequence name from an EditPlanClip object.
 * Mirrors ScaleCut's naming convention so sequences are easy to identify.
 *
 * Status: ✅ READY
 *
 * @param  {Object} clip  One item from edit_plan.json.
 * @return {string}       e.g. "ACME_PODCAST_Clip01_INSTA_9x16"
 */
ScaleCut.buildSequenceName = function(clip) {
    return clip.export_filename
        ? clip.export_filename.replace(".mp4", "").replace(".mov", "").replace(".mxf", "")
        : clip.clip_id + "_" + clip.platform.replace(/ /g, "_") + "_" + clip.format;
};


