/**
 * Create Premiere Pro markers on the active sequence for every clip
 * in the edit plan that has timecodes.
 *
 * Status: 🔧 PARTIAL
 * Works when the active sequence exists and clips have timecodes.
 * Skips placeholder clips (empty start_timecode).
 *
 * @param  {Object}   editPlanData  Parsed edit_plan.json object.
 * @param  {Sequence} [sequence]    Target sequence. Uses active if omitted.
 * @return {number}                 Count of markers created.
 */
ScaleCut.createMarkersFromEditPlan = function(editPlanData, sequence) {
    sequence = sequence || ScaleCut.findActiveSequence();
    if (!sequence) return 0;

    var fps     = editPlanData.fps || ScaleCut.DEFAULT_FPS;
    var clips   = editPlanData.edit_plan || [];
    var created = 0;
    var seen    = {}; // deduplicate: one marker per clip_id (not per deliverable)

    for (var i = 0; i < clips.length; i++) {
        var clip = clips[i];

        // Skip placeholders and already-processed clip_ids
        if (!clip.start_timecode || seen[clip.clip_id]) continue;
        seen[clip.clip_id] = true;

        var startSec = ScaleCut.timecodeToSeconds(clip.start_timecode, fps);
        var endSec   = ScaleCut.timecodeToSeconds(clip.end_timecode,   fps);

        // Build a readable comment from ScaleCut's creative fields
        var commentParts = [];
        if (clip.goal)  commentParts.push("Goal: " + clip.goal);
        if (clip.hook)  commentParts.push("Hook: " + clip.hook);
        if (clip.notes) commentParts.push(clip.notes);

        // ── Premiere API call ──────────────────────────────────────────────
        var marker      = sequence.markers.createMarker(startSec);
        marker.name     = clip.clip_id + (clip.title ? " — " + clip.title : "");
        marker.comments = commentParts.join(" | ");
        marker.end      = endSec;
        marker.type     = ScaleCut.MARKER_TYPES.COMMENT;
        // ──────────────────────────────────────────────────────────────────

        ScaleCut.log("Marker created: " + marker.name +
                     " [" + clip.start_timecode + " → " + clip.end_timecode + "]");
        created++;
    }

    ScaleCut.log("createMarkersFromEditPlan: " + created + " markers created.");
    return created;
};


