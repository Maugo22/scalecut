/**
 * Find and return the active sequence in the current Premiere project.
 * Status: ✅ READY
 *
 * Falls back to the first sequence in the project if none is active.
 * Logs an error if the project has no sequences at all.
 *
 * @return {Sequence|null}
 */
ScaleCut.findActiveSequence = function() {
    if (!app.project) {
        ScaleCut.log("ERROR: No project open in Premiere Pro.");
        return null;
    }

    var seq = app.project.activeSequence;

    if (!seq) {
        ScaleCut.log("WARNING: No active sequence. Trying first available sequence…");

        if (app.project.sequences.numSequences > 0) {
            seq = app.project.sequences[0];
            ScaleCut.log("Using sequence: " + seq.name);
        } else {
            ScaleCut.log("ERROR: Project has no sequences. Create a sequence first.");
            return null;
        }
    }

    ScaleCut.log("Active sequence: " + seq.name + " (" + seq.frameSizeHorizontal + "x" + seq.frameSizeVertical + ")");
    return seq;
};


