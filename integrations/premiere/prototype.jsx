/**
 * Convert a ScaleCut HH:MM:SS:FF timecode to seconds (float).
 * Premiere Pro's marker API accepts time in seconds.
 * Status: ✅ READY
 *
 * @param  {string} tc   Timecode string, e.g. "00:01:25:12".
 * @param  {number} fps  Frame rate (default 25).
 * @return {number}      Time in seconds, or 0 if tc is empty/invalid.
 */
ScaleCut.timecodeToSeconds = function(tc, fps) {
    fps = fps || ScaleCut.DEFAULT_FPS;

    if (!tc || tc.length === 0) return 0;

    var parts = tc.split(":");
    if (parts.length !== 4) return 0;

    var h = parseInt(parts[0], 10) || 0;
    var m = parseInt(parts[1], 10) || 0;
    var s = parseInt(parts[2], 10) || 0;
    var f = parseInt(parts[3], 10) || 0;

    return h * 3600 + m * 60 + s + (f / fps);
};


/**
 * Convert seconds (float) back to HH:MM:SS:FF timecode.
 * Useful for displaying Premiere's time values in ScaleCut format.
 * Status: ✅ READY
 *
 * @param  {number} seconds
 * @param  {number} fps
 * @return {string}  e.g. "00:01:25:12"
 */
ScaleCut.secondsToTimecode = function(seconds, fps) {
    fps = fps || ScaleCut.DEFAULT_FPS;

    var totalFrames = Math.round(seconds * fps);
    var f  = totalFrames % fps;
    var ts = Math.floor(totalFrames / fps);
    var s  = ts % 60;
    var tm = Math.floor(ts / 60);
    var mn = tm % 60;
    var h  = Math.floor(tm / 60);

    function pad(n) { return (n < 10 ? "0" : "") + n; }
    return pad(h) + ":" + pad(mn) + ":" + pad(s) + ":" + pad(f);
};


