/**
 * Main entry point. Called when the script is run directly from
 * File > Scripts > Run Script File, or from a CEP panel via evalScript().
 *
 * Status: 🔧 PARTIAL — markers work; sequence creation is planned.
 *
 * @param  {string} editPlanPath  Absolute path to edit_plan.json.
 *                                Defaults to a hardcoded example path for quick testing.
 * @return {void}
 */
ScaleCut.run = function(editPlanPath) {
    ScaleCut.log("==================================================");
    ScaleCut.log("ScaleCut × Premiere Pro — Prototype v0.1.0");
    ScaleCut.log("==================================================");

    // ── 1. Resolve the edit_plan.json path ────────────────────────────────
    if (!editPlanPath) {
        // Default: look for edit_plan.json next to the current project file
        var projectPath = app.project.path;
        var projectDir  = projectPath.substring(0, projectPath.lastIndexOf("/"));
        editPlanPath    = projectDir + "/10_Admin/edit_plan.json";
        ScaleCut.log("No path provided — trying: " + editPlanPath);
    }

    // ── 2. Load the edit plan ─────────────────────────────────────────────
    var editPlan = ScaleCut.readEditPlanJson(editPlanPath);
    if (!editPlan) {
        ScaleCut.log("FATAL: Could not load edit_plan.json. Aborting.");
        return;
    }

    ScaleCut.log("Project: " + editPlan.project.client + " / " + editPlan.project.project);
    ScaleCut.log("Mode: " + editPlan.mode + " | Total clips: " + editPlan.edit_plan.length);

    // ── 3. Find / validate the active sequence ────────────────────────────
    var masterSeq = ScaleCut.findActiveSequence();
    if (!masterSeq) {
        ScaleCut.log("WARNING: Continuing without an active sequence (some features disabled).");
    }

    // ── 4. Create markers on the master sequence ──────────────────────────
    if (masterSeq) {
        var markersCreated = ScaleCut.createMarkersFromEditPlan(editPlan, masterSeq);
        ScaleCut.log("Markers on master sequence: " + markersCreated);
    }

    // ── 5. Plan subsequences for each deliverable ─────────────────────────
    var sequenceNames = ScaleCut.createSequencesForDeliverables(editPlan);
    ScaleCut.log("Sequences planned: " + sequenceNames.length);

    // ── 6. Summary ────────────────────────────────────────────────────────
    ScaleCut.log("--------------------------------------------------");
    ScaleCut.log("Done. Next steps:");
    ScaleCut.log("  • Fill timecodes in edit_plan.json (if in placeholder mode).");
    ScaleCut.log("  • Re-run the script after adding timecodes.");
    ScaleCut.log("  • When createSubsequenceFromTimecodes() is implemented,");
    ScaleCut.log("    each clip will get its own trimmed sequence automatically.");
    ScaleCut.log("==================================================");
};


