/**
 * Read and parse a ScaleCut edit_plan.json file.
 * Status: ✅ READY
 *
 * @param  {string} filePath  Absolute path to edit_plan.json.
 * @return {Object|null}      Parsed edit plan object, or null on error.
 *
 * @example
 *   var plan = ScaleCut.readEditPlanJson(
 *     "/Users/editor/Desktop/ScaleCut_Projects/ACME_PODCAST_20241220/10_Admin/edit_plan.json"
 *   );
 *   $.writeln("Total clips: " + plan.edit_plan.length);
 */
ScaleCut.readEditPlanJson = function(filePath) {
    var file = new File(filePath);

    if (!file.exists) {
        ScaleCut.log("ERROR: edit_plan.json not found at: " + filePath);
        return null;
    }

    file.open("r");
    var content = file.read();
    file.close();

    if (!content || content.length === 0) {
        ScaleCut.log("ERROR: edit_plan.json is empty.");
        return null;
    }

    try {
        // ExtendScript (ES3) does not guarantee JSON.parse — use eval safely.
        // In Premiere CC 2020+ you can use JSON.parse() directly.
        var data = (typeof JSON !== "undefined")
            ? JSON.parse(content)
            : eval("(" + content + ")");

        ScaleCut.log("Loaded edit_plan.json: " + data.edit_plan.length + " clips, mode=" + data.mode);
        return data;
    } catch (e) {
        ScaleCut.log("ERROR parsing edit_plan.json: " + e.message);
        return null;
    }
};


/**
 * Read and parse a ScaleCut markers.csv file.
 * Status: ✅ READY
 *
 * @param  {string} filePath  Absolute path to markers.csv.
 * @return {Array|null}       Array of row objects, or null on error.
 *
 * @example
 *   var markers = ScaleCut.readMarkersCsv(
 *     "/Users/editor/.../10_Admin/markers.csv"
 *   );
 */
ScaleCut.readMarkersCsv = function(filePath) {
    var file = new File(filePath);

    if (!file.exists) {
        ScaleCut.log("ERROR: markers.csv not found at: " + filePath);
        return null;
    }

    file.open("r");
    var headers = file.readln().split(",");
    var rows    = [];

    while (!file.eof) {
        var line = file.readln();
        if (!line || line.length === 0) continue;

        var values = line.split(",");
        var row    = {};
        for (var i = 0; i < headers.length; i++) {
            row[headers[i].replace(/\r/g, "")] = (values[i] || "").replace(/\r/g, "");
        }
        rows.push(row);
    }

    file.close();
    ScaleCut.log("Loaded markers.csv: " + rows.length + " rows.");
    return rows;
};


